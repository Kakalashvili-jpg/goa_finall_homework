// დავალება 1: Function Expression (ცვლადში შენახული ფუნქცია)
// შექმენი ფუნქცია Function Expression-ის გამოყენებით (ცვლადში რომ ვინახავთ), სახელად checkPassword, რომელსაც გადაეცემა 1 არგუმენტი: password (სტრინგი).

